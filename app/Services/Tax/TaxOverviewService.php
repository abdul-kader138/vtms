<?php

namespace App\Services\Tax;

use App\Enums\IncomeSource;
use App\Enums\PaymentStatus;
use App\Enums\TaxPaymentType;
use App\Models\Customer;
use App\Models\DirittoAnnualePayment;
use App\Models\FatturaTraPrivatiCalculation;
use App\Models\FatturaTraPrivatiPayment;
use App\Models\InailCalculation;
use App\Models\InailPayment;
use App\Models\IncomeData;
use App\Models\InpsCalculation;
use App\Models\InpsPayment;
use App\Models\Setting;
use App\Models\TaxCalculation;
use App\Models\TaxPayment;
use App\Support\Tax\TaxRules;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Support\Collection;

class TaxOverviewService
{
    public const PAYMENT_TYPES = ['tax', 'inps', 'inail', 'diritto_annuale', 'fattura_tra_privati'];

    public function __construct(private readonly IncomePredictionService $predictionService) {}

    public function build(Customer $customer, int $year): array
    {
        $tax = TaxCalculation::where('customer_id', $customer->id)->where('tax_year', $year)->first();
        $payments = $this->payments($customer, $year);

        return [
            'year' => $year,
            'tax' => $tax,
            'estimate' => $tax ? null : $this->liveEstimate($customer, $year),
            'prediction' => $this->predictionService->predict($customer, $year),
            'inps' => InpsCalculation::where('customer_id', $customer->id)->where('tax_year', $year)->first(),
            'inail' => InailCalculation::where('customer_id', $customer->id)->where('tax_year', $year)->first(),
            'fattura_tra_privati' => FatturaTraPrivatiCalculation::where('customer_id', $customer->id)->where('tax_year', $year)->first(),
            'previous_year_inps' => InpsCalculation::where('customer_id', $customer->id)->where('tax_year', $year - 1)->value('inps_amount_after_discount'),
            'payments' => $payments,
            'summary' => $this->summary($payments),
            'warnings' => [...$this->eligibilityWarnings($customer, $year, $tax), ...$this->collectionWarnings($customer, $year), ...$this->stampDutyWarnings($customer, $year)],
        ];
    }

    /**
     * The payments generated by year Y's calculation: Y's own balance plus
     * the two advances it scheduled toward Y+1 (stored with tax_year = Y+1,
     * see PaymentScheduleService::scheduleTaxPayments()). Matches what
     * VTMS's admin view listed for a tax year.
     *
     * @return array<string, Collection>
     */
    public function payments(Customer $customer, int $year): array
    {
        $taxPayments = TaxPayment::where('customer_id', $customer->id)
            ->where(function ($q) use ($year) {
                $q->where(fn ($q) => $q->where('tax_year', $year)->where('payment_type', TaxPaymentType::Balance))
                    ->orWhere(fn ($q) => $q->where('tax_year', $year + 1)->whereIn('payment_type', [TaxPaymentType::FirstAdvance, TaxPaymentType::SecondAdvance]));
            })
            ->orderBy('due_date')
            ->get();

        return [
            'tax' => $taxPayments,
            // Like the tax advances: the year's own installments, plus the
            // advances toward next year that this year's calculation set.
            'inps' => InpsPayment::with('customer')->where('customer_id', $customer->id)
                ->where(function ($q) use ($year) {
                    $advances = [PaymentScheduleService::INPS_EXCESS_FIRST_ADVANCE, PaymentScheduleService::INPS_EXCESS_SECOND_ADVANCE];
                    $q->where(fn ($q) => $q->where('payment_year', $year)->whereNotIn('installment_number', $advances))
                        ->orWhere(fn ($q) => $q->where('payment_year', $year + 1)->whereIn('installment_number', $advances));
                })
                ->orderBy('due_date')->orderBy('installment_number')->get(),
            'inail' => InailPayment::where('customer_id', $customer->id)->where('payment_year', $year)->get(),
            'diritto_annuale' => DirittoAnnualePayment::where('customer_id', $customer->id)->where('payment_year', $year)->get(),
            'fattura_tra_privati' => FatturaTraPrivatiPayment::where('customer_id', $customer->id)->where('payment_year', $year)->get(),
        ];
    }

    /**
     * Shown when no calculation has been run for the year yet — VTMS's
     * customer dashboard "live data" block, recomputed from income_data on
     * every view instead of persisted.
     */
    public function liveEstimate(Customer $customer, int $year): ?array
    {
        $totalSales = (float) IncomeData::where('customer_id', $customer->id)->revenueForYear($year)->sum('taxable_sales');

        if ($totalSales <= 0) {
            return null;
        }

        $coefficient = (float) $customer->coefficient_of_profitability;
        $taxRate = (float) $customer->tax_rate;
        $taxableIncome = round($totalSales * $coefficient / 100, 2);

        return [
            'total_sales' => round($totalSales, 2),
            'taxable_income' => $taxableIncome,
            'coefficient_used' => $coefficient,
            'tax_rate' => $taxRate,
            'estimated_tax' => round($taxableIncome * $taxRate / 100, 2),
        ];
    }

    public static function effectiveStatus(Model $payment): string
    {
        $status = $payment->status instanceof PaymentStatus ? $payment->status : PaymentStatus::tryFrom((string) $payment->status);

        if ($status === PaymentStatus::Paid || $status === PaymentStatus::Cancelled) {
            return $status->value;
        }

        if ($status === PaymentStatus::Overdue || ($payment->due_date && $payment->due_date->lt(today()))) {
            return PaymentStatus::Overdue->value;
        }

        return PaymentStatus::Pending->value;
    }

    /**
     * @param  array<string, Collection>  $payments
     */
    public function summary(array $payments): array
    {
        $summary = ['total_due' => 0.0, 'total_paid' => 0.0, 'total_overdue' => 0.0, 'total_upcoming' => 0.0, 'overdue_count' => 0, 'upcoming_count' => 0, 'paid_count' => 0];

        foreach ($payments as $collection) {
            foreach ($collection as $payment) {
                $status = self::effectiveStatus($payment);
                $paid = (float) $payment->paid_amount;

                if ($status === PaymentStatus::Cancelled->value) {
                    continue;
                }

                $summary['total_paid'] += $paid;

                if ($status === PaymentStatus::Paid->value) {
                    $summary['paid_count']++;

                    continue;
                }

                $outstanding = max(0, (float) $payment->amount - $paid);
                $summary['total_due'] += $outstanding;

                if ($status === PaymentStatus::Overdue->value) {
                    $summary['total_overdue'] += $outstanding;
                    $summary['overdue_count']++;
                } else {
                    $summary['total_upcoming'] += $outstanding;
                    $summary['upcoming_count']++;
                }
            }
        }

        foreach (['total_due', 'total_paid', 'total_overdue', 'total_upcoming'] as $key) {
            $summary[$key] = round($summary[$key], 2);
        }

        return $summary;
    }

    /**
     * Invoices above €77.47 sent without the virtual stamp: the Agenzia adds
     * them to the quarterly bill anyway, and the invoice was legally wrong.
     *
     * @return list<array{level: string, message: string}>
     */
    public function stampDutyWarnings(Customer $customer, int $year): array
    {
        if (! TaxRules::isLaw()) {
            return [];
        }

        $threshold = (float) Setting::get('stamp_duty_threshold', 77.47);
        $missing = IncomeData::where('customer_id', $customer->id)->where('tax_year', $year)
            ->where('source', IncomeSource::SdiFattura)
            ->where(fn ($q) => $q->where('sales_amount', '>', $threshold)->orWhere('sales_amount', '<', -$threshold))
            ->where(fn ($q) => $q->whereNull('meta->bollo_virtuale')->orWhereNotIn('meta->bollo_virtuale', ['SI', 'Si', 'si']))
            ->count();

        return $missing === 0 ? [] : [[
            'level' => 'warning',
            'message' => __(':n invoices of :year over €77.47 were sent without the virtual stamp duty. The €2 is still due for each (included in the stamp duty below); set "Bollo virtuale" on future invoices.', ['n' => $missing, 'year' => $year]),
        ]];
    }

    /**
     * Law rules tax on a cash basis: invoices of the year not collected yet
     * are left out of its revenue until they are.
     *
     * @return list<array{level: string, message: string}>
     */
    public function collectionWarnings(Customer $customer, int $year): array
    {
        if (! TaxRules::isLaw()) {
            return [];
        }

        $open = IncomeData::where('customer_id', $customer->id)->where('tax_year', $year)->whereNull('collected_on');
        $count = (clone $open)->count();

        if ($count === 0) {
            return [];
        }

        return [[
            'level' => 'info',
            'message' => __(':n invoices of :year (:amount) are not collected yet, so they are not in this year\'s revenue. They count in the year they are paid.', [
                'n' => $count,
                'year' => $year,
                'amount' => '€'.number_format((float) $open->sum('taxable_sales'), 2, ',', '.'),
            ]),
        ]];
    }

    /**
     * Regime Forfettario eligibility. Above the customer's annual revenue
     * limit (€85k by default) the regime ends from 1 January of the next
     * year; above the immediate-exit threshold (€100k, configurable in Tax
     * Settings) it ends immediately and VAT applies from the invoice that
     * crossed it.
     *
     * @return list<array{level: string, message: string}>
     */
    public function eligibilityWarnings(Customer $customer, int $year, ?TaxCalculation $tax): array
    {
        // Null on a model created in this request (the DB default isn't
        // read back), so fall back to the same €85k default.
        $limit = (float) ($customer->annual_revenue_limit ?? 85000);
        $immediateThreshold = (float) Setting::get('forfettario_immediate_exit_threshold', 100000);

        $sales = $tax
            ? (float) $tax->total_sales
            : (float) IncomeData::where('customer_id', $customer->id)->revenueForYear($year)->sum('taxable_sales');

        $fmt = fn (float $v) => '€'.number_format($v, 2, ',', '.');

        if ($immediateThreshold > 0 && $sales > $immediateThreshold) {
            return [[
                'level' => 'danger',
                'message' => __('Revenue :sales exceeds :threshold — the customer leaves Regime Forfettario immediately in :year and VAT applies from the invoice that crossed the threshold.', ['sales' => $fmt($sales), 'threshold' => $fmt($immediateThreshold), 'year' => $year]),
            ]];
        }

        if ($limit > 0 && $sales > $limit) {
            return [[
                'level' => 'warning',
                'message' => __('Revenue :sales exceeds the :limit limit — the customer is no longer eligible for Regime Forfettario from 1 January :next.', ['sales' => $fmt($sales), 'limit' => $fmt($limit), 'next' => $year + 1]),
            ]];
        }

        $prediction = $this->predictionService->predict($customer, $year);

        if ($limit > 0 && $prediction && $prediction['missing_months'] !== [] && $prediction['predicted_total_sales'] > $limit) {
            return [[
                'level' => 'info',
                'message' => __('At the current pace revenue is projected to reach :predicted, above the :limit Regime Forfettario limit.', ['predicted' => $fmt($prediction['predicted_total_sales']), 'limit' => $fmt($limit)]),
            ]];
        }

        return [];
    }
}
